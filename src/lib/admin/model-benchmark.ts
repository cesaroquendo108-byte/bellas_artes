export function calculateModelBenchmarkScore(entry: ModelBenchmarkEntry) {
  return Math.round(
    entry.scores.license * MODEL_BENCHMARK_WEIGHTS.license
      + entry.scores.gpuFit * MODEL_BENCHMARK_WEIGHTS.gpuFit
      + entry.scores.productFit * MODEL_BENCHMARK_WEIGHTS.productFit
      + entry.scores.integration * MODEL_BENCHMARK_WEIGHTS.integration,
  );
}

export function listModelBenchmark() {
  return ADMIN_MODEL_BENCHMARK.map((entry) => ({
    ...entry,
    score: calculateModelBenchmarkScore(entry),
  })).sort((left, right) => right.score - left.score);
}

export function summarizeModelBenchmark() {
  const models = listModelBenchmark();
  return {
    total: models.length,
    smokePassed: models.filter((model) => model.evidence === "smoke_passed").length,
    implementNext: models.filter((model) => model.decision === "implement_next").length,
    benchmarkNext: models.filter((model) => model.decision === "benchmark_next").length,
    researchOnly: models.filter((model) => model.decision === "research_only").length,
    replacedOrDiscarded: models.filter((model) => model.decision === "replace" || model.decision === "discard").length,
  };
}

